-- 2. Add location columns to sales_orders
ALTER TABLE public.sales_orders
ADD COLUMN IF NOT EXISTS order_latitude double precision,
ADD COLUMN IF NOT EXISTS order_longitude double precision;

-- 3. Create salesman_punches table
CREATE TABLE IF NOT EXISTS public.salesman_punches (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    salesman_id uuid not null references public.users(id) on delete cascade,
    company_id text,
    latitude double precision not null,
    longitude double precision not null,
    notes text
);

-- Enable RLS for salesman_punches (optional but good practice)
ALTER TABLE public.salesman_punches ENABLE ROW LEVEL SECURITY;

-- Create policy to allow all for now (adjust according to your security requirements)
CREATE POLICY "Enable all for authenticated users" ON public.salesman_punches
    FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- 4. Create customer_salesman_assignments for many-to-many relationship
CREATE TABLE IF NOT EXISTS public.customer_salesman_assignments (
    customer_id uuid REFERENCES public.customers(id) ON DELETE CASCADE,
    salesman_id uuid REFERENCES public.users(id) ON DELETE CASCADE,
    company_id text,
    PRIMARY KEY (customer_id, salesman_id)
);

-- Enable RLS for customer_salesman_assignments
ALTER TABLE public.customer_salesman_assignments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Enable all for authenticated users" ON public.customer_salesman_assignments FOR ALL TO authenticated USING (true) WITH CHECK (true);

